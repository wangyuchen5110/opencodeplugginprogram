import fs from "node:fs"
import path from "node:path"
import os from "node:os"
import { spawnSync, execFileSync } from "node:child_process"
import { stripJsonc } from "./discover.mjs"

export const PACKAGE_NAME = "opencode-skills-doctor"
const PLUGIN_FILE = "skills-doctor.js"
const COMMAND_FILE = "skills-doctor.md"

const V1_PLUGIN_SOURCE = `// Generated by skills-doctor install\n// OpenCode 1.x plugin entry\nexport { SkillsDoctorPlugin } from "opencode-skills-doctor/v1"\n`

const V1_COMMAND = `---
description: Audit local skills with skills-doctor
---
Use the skills_doctor tool to audit the skills in this project. Summarize the top findings and propose concrete fixes (archive shadowed duplicates, hide low-frequency skills). $ARGUMENTS
`

export function defaultConfigDir() {
  const base = process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config")
  return path.join(base, "opencode")
}

function readJsonc(file) {
  return JSON.parse(stripJsonc(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "")))
}

function writeJson(file, data) {
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + "\n", "utf8")
}

function readText(file) {
  try {
    return fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "")
  } catch {
    return null
  }
}

function detectVersion() {
  try {
    const out = execFileSync("opencode", ["--version"], { encoding: "utf8", timeout: 15000 })
    const match = /(\d+)\.(\d+)\.(\d+)/.exec(String(out))
    if (match) return match[0]
  } catch {}
  return null
}

function configFile(dir) {
  const candidates = ["opencode.jsonc", "opencode.json"]
    .map((name) => path.join(dir, name))
    .filter((file) => fs.existsSync(file))

  // 优先沿用已经在配置 plugin/plugins 的文件，避免把插件写进另一个配置文件后被覆盖
  for (const file of candidates) {
    try {
      const config = readJsonc(file)
      if (config.plugin !== undefined || config.plugins !== undefined) return file
    } catch {}
  }

  return candidates[0] ?? path.join(dir, "opencode.json")
}

function backup(file, stamp) {
  if (!fs.existsSync(file)) return null
  const target = `${file}.bak-${stamp}`
  fs.copyFileSync(file, target)
  return target
}

function ensureUniqueEntry(list, entry) {
  if (!Array.isArray(list)) return [entry]
  return list.includes(entry) ? list : [...list, entry]
}

function installPackage(dir) {
  const npm = process.platform === "win32" ? "npm.cmd" : "npm"
  const result = spawnSync(npm, ["install", "--prefix", dir, PACKAGE_NAME + "@latest", "--no-audit", "--no-fund"], {
    stdio: "inherit",
    env: process.env,
    timeout: 180000,
  })
  return result.status === 0
}

/**
 * 把 skills-doctor 装进 OpenCode：
 * - 2.x：写入 plugins 数组（OpenCode 自己从 npm 拉包）
 * - 1.x：在配置目录安装包、写本地插件入口、写 /skills-doctor 命令、补插件数组
 */
export function installOpenCode({ configDir = defaultConfigDir(), version = null, dryRun = false, installPackage: withPackage = true } = {}) {
  const dir = path.resolve(configDir)
  const actions = []
  const errors = []
  const dry = (message) => actions.push(`[dry-run] ${message}`)
  const act = (message) => actions.push(message)

  const cfgFile = configFile(dir)
  const existingText = readText(cfgFile)
  let config = {}
  if (existingText !== null) {
    try {
      config = readJsonc(cfgFile)
    } catch (err) {
      errors.push(`cannot parse ${cfgFile}: ${err.message}`)
      return { version, major: null, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
    }
  }

  const resolvedVersion = version ?? detectVersion()
  const inferredMajor = config.plugin !== undefined ? 1 : 2
  const major = resolvedVersion ? Number(resolvedVersion.split(".")[0]) : inferredMajor

  if (dryRun) dry(`config dir: ${dir}`)
  if (!fs.existsSync(dir)) {
    if (!dryRun) fs.mkdirSync(dir, { recursive: true })
    act(`created config dir ${dir}`)
  }

  const stamp = new Date().toISOString().replace(/[:.]/g, "-")

  if (major >= 2) {
    const next = { ...config, plugins: ensureUniqueEntry(config.plugins, PACKAGE_NAME) }
    const changed = !Array.isArray(config.plugins) || !config.plugins.includes(PACKAGE_NAME)
    if (changed) {
      if (!dryRun) {
        const backupFile = backup(cfgFile, stamp)
        if (backupFile) act(`backup ${backupFile}`)
        writeJson(cfgFile, next)
        act(`added "${PACKAGE_NAME}" to plugins in ${cfgFile}`)
      } else dry(`add "${PACKAGE_NAME}" to plugins in ${cfgFile}`)
    } else {
      act(`plugins already contains "${PACKAGE_NAME}"`)
    }
    act("restart OpenCode; the /skills-doctor command and skills_doctor tool will be available")
    return { version: resolvedVersion, major, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
  }

  // 1.x
  const pluginFile = path.join(dir, "plugins", PLUGIN_FILE)
  const commandFile = path.join(dir, "command", COMMAND_FILE)
  const pluginPath = pluginFile

  const hasPackage = fs.existsSync(path.join(dir, "node_modules", PACKAGE_NAME, "package.json"))
  if (!hasPackage) {
    if (withPackage && !dryRun) {
      act(`installing ${PACKAGE_NAME} into ${dir}`)
      if (!installPackage(dir)) errors.push(`npm install failed for ${PACKAGE_NAME}`)
      else act(`installed ${PACKAGE_NAME}`)
    } else if (dryRun) {
      dry(`install ${PACKAGE_NAME} into ${dir}`)
    } else {
      act(`skipped npm install; run: npm i --prefix "${dir}" ${PACKAGE_NAME}`)
    }
  } else {
    act(`${PACKAGE_NAME} already installed in ${dir}`)
  }

  if (!fs.existsSync(pluginFile)) {
    if (!dryRun) {
      fs.mkdirSync(path.dirname(pluginFile), { recursive: true })
      fs.writeFileSync(pluginFile, V1_PLUGIN_SOURCE, "utf8")
      act(`wrote plugin entry ${pluginFile}`)
    } else dry(`write plugin entry ${pluginFile}`)
  } else {
    act(`plugin entry already exists ${pluginFile}`)
  }

  if (!fs.existsSync(commandFile)) {
    if (!dryRun) {
      fs.mkdirSync(path.dirname(commandFile), { recursive: true })
      fs.writeFileSync(commandFile, V1_COMMAND, "utf8")
      act(`wrote command ${commandFile}`)
    } else dry(`write command ${commandFile}`)
  } else {
    act(`command already exists ${commandFile}`)
  }

  const nextPlugin = ensureUniqueEntry(config.plugin, pluginPath)
  const pluginChanged = !Array.isArray(config.plugin) || !config.plugin.includes(pluginPath)
  if (pluginChanged) {
    if (!dryRun) {
      const backupFile = backup(cfgFile, stamp)
      if (backupFile) act(`backup ${backupFile}`)
      writeJson(cfgFile, { ...config, plugin: nextPlugin })
      act(`added plugin entry to ${cfgFile}`)
    } else dry(`add plugin entry to ${cfgFile}`)
  } else {
    act("plugin array already configured")
  }

  const pkgFile = path.join(dir, "package.json")
  const pkgText = readText(pkgFile)
  let pkg = {}
  if (pkgText !== null) {
    try {
      pkg = JSON.parse(pkgText)
    } catch {}
  }
  if (pkg.type !== "module") {
    if (!dryRun) {
      pkg.type = "module"
      fs.writeFileSync(pkgFile, JSON.stringify(pkg, null, 2) + "\n", "utf8")
      act(`set "type": "module" in ${pkgFile}`)
    } else dry(`set "type": "module" in ${pkgFile}`)
  }

  act("restart OpenCode; the skills_doctor tool and /skills-doctor command will be available")
  return { version: resolvedVersion, major, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
}

function removePackage(dir) {
  const npm = process.platform === "win32" ? "npm.cmd" : "npm"
  const result = spawnSync(npm, ["uninstall", "--prefix", dir, PACKAGE_NAME, "--no-audit", "--no-fund"], {
    stdio: "inherit",
    env: process.env,
    timeout: 180000,
  })
  return result.status === 0
}

/**
 * 撤销 install：移除配置里的插件条目、删除安装器生成的文件、可选卸载 npm 包。
 * 只删除「由安装器生成」的文件，用户自己改过的一律保留并提示。
 */
export function uninstallOpenCode({ configDir = defaultConfigDir(), version = null, dryRun = false, removePackage: withPackage = true } = {}) {
  const dir = path.resolve(configDir)
  const actions = []
  const errors = []
  const dry = (message) => actions.push(`[dry-run] ${message}`)
  const act = (message) => actions.push(message)

  const cfgFile = configFile(dir)
  const existingText = readText(cfgFile)
  let config = {}
  if (existingText !== null) {
    try {
      config = readJsonc(cfgFile)
    } catch (err) {
      errors.push(`cannot parse ${cfgFile}: ${err.message}`)
      return { version, major: null, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
    }
  }

  const resolvedVersion = version ?? detectVersion()
  const inferredMajor = config.plugin !== undefined ? 1 : 2
  const major = resolvedVersion ? Number(resolvedVersion.split(".")[0]) : inferredMajor
  const stamp = new Date().toISOString().replace(/[:.]/g, "-")

  if (major >= 2) {
    if (Array.isArray(config.plugins) && config.plugins.includes(PACKAGE_NAME)) {
      const next = config.plugins.filter((entry) => entry !== PACKAGE_NAME)
      if (!dryRun) {
        const backupFile = backup(cfgFile, stamp)
        if (backupFile) act(`backup ${backupFile}`)
        writeJson(cfgFile, { ...config, plugins: next })
        act(`removed "${PACKAGE_NAME}" from plugins in ${cfgFile}`)
      } else dry(`remove "${PACKAGE_NAME}" from plugins in ${cfgFile}`)
    } else {
      act(`"${PACKAGE_NAME}" is not configured in plugins`)
    }
    act("restart OpenCode to finish removal")
    return { version: resolvedVersion, major, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
  }

  const pluginFile = path.join(dir, "plugins", PLUGIN_FILE)
  const commandFile = path.join(dir, "command", COMMAND_FILE)

  if (Array.isArray(config.plugin) && config.plugin.includes(pluginFile)) {
    const next = config.plugin.filter((entry) => entry !== pluginFile)
    if (!dryRun) {
      const backupFile = backup(cfgFile, stamp)
      if (backupFile) act(`backup ${backupFile}`)
      writeJson(cfgFile, { ...config, plugin: next })
      act(`removed plugin entry from ${cfgFile}`)
    } else dry(`remove plugin entry from ${cfgFile}`)
  } else {
    act("plugin entry is not configured")
  }

  if (fs.existsSync(pluginFile)) {
    const content = readText(pluginFile) ?? ""
    const generated =
      content.includes("Generated by skills-doctor install") ||
      (content.includes("SkillsDoctorPlugin") && content.includes("opencode-skills-doctor/v1"))
    if (generated) {
      if (!dryRun) {
        fs.rmSync(pluginFile, { force: true })
        act(`deleted ${pluginFile}`)
      } else dry(`delete ${pluginFile}`)
    } else {
      act(`kept ${pluginFile} (not generated by skills-doctor)`)
    }
  }

  if (fs.existsSync(commandFile)) {
    const content = readText(commandFile) ?? ""
    if (content.includes("skills_doctor tool")) {
      if (!dryRun) {
        fs.rmSync(commandFile, { force: true })
        act(`deleted ${commandFile}`)
      } else dry(`delete ${commandFile}`)
    } else {
      act(`kept ${commandFile} (not generated by skills-doctor)`)
    }
  }

  const hasPackage = fs.existsSync(path.join(dir, "node_modules", PACKAGE_NAME, "package.json"))
  if (withPackage && hasPackage) {
    if (dryRun) {
      dry(`uninstall ${PACKAGE_NAME} from ${dir}`)
    } else {
      act(`uninstalling ${PACKAGE_NAME} from ${dir}`)
      if (removePackage(dir)) act(`uninstalled ${PACKAGE_NAME}`)
      else errors.push(`npm uninstall failed for ${PACKAGE_NAME}`)
    }
  }

  act("restart OpenCode to finish removal")
  return { version: resolvedVersion, major, configDir: dir, configFile: cfgFile, actions, errors, dryRun }
}
